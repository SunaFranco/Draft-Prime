-- Draft Prime: authenticated profiles, room membership, invitations and history.
-- Apply in the Supabase SQL Editor after reviewing the preconditions below.
-- This migration intentionally deletes all legacy anonymous game sessions.

begin;

-- The product decision is to close every anonymous room during migration.
-- These records are transient live state, not the new per-user history.
delete from public.game_sessions;

create table if not exists public.profiles (
    id uuid primary key references auth.users (id) on delete cascade,
    username text not null,
    display_name text not null,
    avatar_key text not null default 'avatar_01',
    is_admin boolean not null default false,
    must_change_password boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint profiles_username_length check (char_length(username) between 3 and 24),
    constraint profiles_display_name_length check (char_length(display_name) between 1 and 40),
    constraint profiles_avatar_key_format check (avatar_key ~ '^avatar_[0-9]{2}$')
);

create unique index if not exists profiles_username_lower_unique
    on public.profiles (lower(username));

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create or replace function private.create_profile_for_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    insert into public.profiles (id, username, display_name, avatar_key, is_admin, must_change_password)
    values (
        new.id,
        coalesce(nullif(new.raw_user_meta_data ->> 'username', ''), split_part(new.email, '@', 1)),
        coalesce(nullif(new.raw_user_meta_data ->> 'display_name', ''), split_part(new.email, '@', 1)),
        coalesce(nullif(new.raw_user_meta_data ->> 'avatar_key', ''), 'avatar_01'),
        coalesce((new.raw_user_meta_data ->> 'is_admin')::boolean, false),
        coalesce((new.raw_user_meta_data ->> 'must_change_password')::boolean, true)
    )
    on conflict (id) do nothing;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
    after insert on auth.users
    for each row execute procedure private.create_profile_for_auth_user();
revoke all on function private.create_profile_for_auth_user() from public, anon, authenticated;

alter table public.game_sessions
    add column if not exists created_by uuid references public.profiles (id) on delete set null,
    add column if not exists status text not null default 'active',
    add column if not exists finish_type text,
    add column if not exists finished_at timestamptz;

create table if not exists public.game_session_members (
    session_id text not null references public.game_sessions (session_id) on delete cascade,
    user_id uuid not null references public.profiles (id) on delete cascade,
    joined_at timestamptz not null default now(),
    primary key (session_id, user_id)
);

create table if not exists public.game_session_invites (
    id uuid primary key default gen_random_uuid(),
    session_id text not null references public.game_sessions (session_id) on delete cascade,
    invited_user_id uuid not null references public.profiles (id) on delete cascade,
    invited_by uuid not null references public.profiles (id) on delete restrict,
    status text not null default 'pending',
    created_at timestamptz not null default now(),
    responded_at timestamptz,
    constraint game_session_invites_status_check
        check (status in ('pending', 'accepted', 'declined', 'cancelled'))
);

create unique index if not exists one_pending_invite_per_user_per_room
    on public.game_session_invites (session_id, invited_user_id)
    where status = 'pending';

create table if not exists public.user_room_history (
    id bigint generated by default as identity primary key,
    session_id text not null references public.game_sessions (session_id) on delete cascade,
    user_id uuid not null references public.profiles (id) on delete cascade,
    room_name text not null default 'Sala anterior',
    mode text,
    started_at timestamptz,
    finished_at timestamptz not null,
    result_summary jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    constraint user_room_history_one_record_per_user unique (session_id, user_id)
);

create table if not exists public.trophies (
    id text primary key,
    title text not null,
    description text not null default '',
    icon_key text not null,
    pokemon_ids integer[] not null default '{}',
    created_at timestamptz not null default now()
);

create table if not exists public.user_trophies (
    user_id uuid not null references public.profiles (id) on delete cascade,
    trophy_id text not null references public.trophies (id) on delete restrict,
    earned_at timestamptz not null default now(),
    source_session_id text references public.game_sessions (session_id) on delete set null,
    primary key (user_id, trophy_id, earned_at)
);

-- Values are enforced here as well as in the backend.
alter table public.game_sessions
    drop constraint if exists game_sessions_status_check,
    add constraint game_sessions_status_check
        check (status in ('active', 'finished_natural', 'finished_forced')),
    drop constraint if exists game_sessions_finish_type_check,
    add constraint game_sessions_finish_type_check
        check (finish_type is null or finish_type in ('natural', 'forced'));

create index if not exists game_session_members_user_idx
    on public.game_session_members (user_id, joined_at desc);
create index if not exists game_session_invites_user_status_idx
    on public.game_session_invites (invited_user_id, status, created_at desc);
create index if not exists user_room_history_user_finished_idx
    on public.user_room_history (user_id, finished_at desc);
create index if not exists user_trophies_user_idx
    on public.user_trophies (user_id, earned_at desc);

-- All reads/writes for these tables go through the authenticated backend.
-- No anon/authenticated policies are created; keep the service-role key server-side only.
alter table public.profiles enable row level security;
alter table public.game_sessions enable row level security;
alter table public.game_session_members enable row level security;
alter table public.game_session_invites enable row level security;
alter table public.user_room_history enable row level security;
alter table public.trophies enable row level security;
alter table public.user_trophies enable row level security;

commit;
